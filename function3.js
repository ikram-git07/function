//  qui prend deux nombres en paramètres et retourne le plus grand des deux. 
// Utilisez cette fonction pour afficher le maximum entre deux nombres.
function max (ikram, meryem){
    if (ikram > meryem){
         return ikram
    }
       else {
        return meryem
       }
}
const resultat = max (15, 20);
